def order_text(service, username, price, discount=0, final_price=None):
    if final_price is None:
        final_price = price

    text = f"""
🧾 سفارش شما

📦 سرویس: {service['name']}
👤 نام کاربری: {username}

💰 قیمت اصلی: {price:,} تومان
"""

    if discount:
        text += f"🎟️ تخفیف: {discount}%\n"

    text += f"""
💵 مبلغ قابل پرداخت: {final_price:,} تومان

💳 اطلاعات پرداخت:

کارت:
{{PAYMENT_CARD}}

به نام:
{{PAYMENT_NAME}}

بعد از پرداخت، رسید خود را ارسال کنید.
"""

    return text


